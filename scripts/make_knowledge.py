def doc_guide() -> Path:
    content = """# 学生参赛指南：从报名到报销

本指南面向首次参加学科竞赛的本科生，梳理完整流程与常见问题。

## 一、参赛前：选赛事

学院每年 3 月发布《学科竞赛目录》，按 A、B、C 三类列出全年赛事。
选赛事时重点看三件事：

1. 专业适配。目录中标注了每个赛事适配的专业，跨专业参赛需指导教师同意。
2. 时间冲突。同一学期参赛不超过两项，避免影响课程学习。
3. 备赛周期。程序设计类赛事通常需要 2-3 个月准备，创新创业类需要 4-6 个月。

新生建议从校级程序设计新生赛、蓝桥杯省赛起步，积累经验后再冲 ACM 区域赛和国创赛。

## 二、组队与找导师

团队赛一般 3-5 人，建议专业结构互补。例如参加国创赛，理想配置是
技术（计算机/人工智能）+ 商业分析（经管）+ 设计（数媒）。

指导教师可在学院网站"师资队伍"页面按研究方向筛选，也可由系主任推荐。
确定导师后，需请导师在报名表上签字。

## 三、报名流程

1. 填写《学科竞赛参赛报名表》，一队一表。
2. 指导教师签字。
3. 系主任审核。
4. 报竞赛秘书汇总，由学院统一报送组委会。

注意：学院内部审核截止时间通常比组委会截止时间提前 5 个工作日，
以学院通知为准，不要卡着组委会的时间报名。

## 四、经费申请

- 报名前 15 个工作日提交《学科竞赛经费预算申请表》。
- 预算须逐项列明科目、数量、单价，并附预算说明。
- 单队预算 5000 元以下由分管副院长审批，5000-12000 元由院长审批。
- 预算批准后可办理借款，借款须在赛后 30 日内冲账。

开支标准速查：省外交通 700 元/人次、住宿 380 元/人天、伙食补助 100 元/人天；
省内交通 220 元/人次、住宿 280 元/人天、伙食补助 80 元/人天。
报名费单队上限 1500 元，材料费单队上限 1000 元。

## 五、备赛与提交

材料提交前务必对照规程逐项自查：

- 文件格式与大小是否符合要求（如视频不超过 200MB）
- 页数是否超限
- 是否遗漏签字、盖章
- 图表是否清晰、编号是否连续

建议提前 48 小时完成提交，留出应对系统故障的时间。

## 六、报销

赛后 30 日内提交报销单，材料包括：

1. 报销单
2. 原始发票（抬头为学校全称，不得开个人）
3. 行程单或签到表
4. 竞赛通知
5. 参赛审批表
6. 预算批复单
7. 获奖证书复印件（如获奖）

不予报销的常见情形：餐饮发票、礼品、个人电子设备、无票支出、超预算部分。

## 七、常见问题

**问：可以同时参加两个赛事吗？**
可以，但每学期不超过两项，且不得在同一时间参加两个需要现场参赛的赛事。

**问：报名费谁出？**
校级赛事不收费。省级以上赛事报名费由学院承担，单队上限 1500 元。

**问：没获奖能报销吗？**
可以。经费支持参赛行为本身，不以获奖为前提。

**问：获奖后奖金怎么发？**
奖金按队伍发放至队长账户，由队长按贡献分配。学院另有获奖表彰。

**问：能用 AI 工具写代码吗？**
ACM 等程序设计类赛事明确禁止使用生成式 AI 代写代码，赛后有代码查重。
其他赛事允许使用 AI 辅助，但须在材料中说明使用情况。
"""
